import logging

from app.core.config import settings

level = settings.LOG_LEVEL


def setup_logging() -> None:
    logging.basicConfig(
        level=level,
        format=(
            "%(asctime)s | "
            "%(levelname)s | "
            "%(name)s | "
            "%(message)s"
        ),
        datefmt="%Y-%m-%d %H:%M:%S",
    )
